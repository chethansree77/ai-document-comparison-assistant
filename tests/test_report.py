
from report_generator import generate_comparison_report
from docx import Document
from io import BytesIO

sample_comparison = """
## 1. SUMMARY OF DOCUMENT A
Document A provides **12 annual leave days** per year.

## 2. SIMILARITIES
- Both documents provide 8 days of sick leave.
- Both require manager approval.

## 3. KEY FACTS

| Fact | Document A | Document B |
|---|---|---|
| Annual Leave | 12 days | 15 days |
| Sick Leave | 8 days | 8 days |

## 4. OVERALL CONCLUSION
Document B increases annual leave from 12 to 15 days.
"""

try:
    report_bytes = generate_comparison_report(
        "document_a.pdf",
        "document_b.pdf",
        sample_comparison
    )

    # Check that the generated bytes form a valid Word document.
    document = Document(BytesIO(report_bytes))

    print("Improved report generation successful!")
    print("File size:", len(report_bytes), "bytes")
    print("Word paragraphs:", len(document.paragraphs))
    print("Word tables:", len(document.tables))

    with open("test_comparison_report.docx", "wb") as output:
        output.write(report_bytes)

    print("Saved: test_comparison_report.docx")

except Exception as error:
    print("Report test failed:")
    print(error)
